function generate_constants_file(name::String)
    # Determine paths relative to this script's location
    # Assuming this script is in Battler/scripts/
    # Navigate up from 'scripts' to 'Battler' directory, then to 'assets'
    project_battler_dir = joinpath(@__DIR__, "..") 
    
    json_file_path = joinpath(project_battler_dir, "assets", "game-data-manager", "json", "$(name).json")
    output_file_path = joinpath(project_battler_dir, "scripts", "utils", "$(name)Constants.jl")

    if !isfile(json_file_path)
        @error "Input JSON file not found: $(json_file_path)"
        println("Please ensure the JSON file exists at the expected location.")
        return
    end

    json_string = ""
    try
        json_string = read(json_file_path, String)
    catch e
        @error "Failed to read JSON file $(json_file_path): $(e)"
        return
    end
    
    data = nothing
    try
        data = JSON3.read(json_string)
    catch e
        @error "Failed to parse JSON data from $(json_file_path): $(e)"
        return
    end

    lines_to_write = String[]
    push!(lines_to_write, "# This file is auto-generated by generate_constants.jl. Do not edit manually.")
    #push!(lines_to_write, "# Generated on: $(Dates.format(Dates.now(), "yyyy-mm-dd HH:MM:SS"))")
    push!(lines_to_write, "# Source JSON: $(basename(json_file_path))")
    push!(lines_to_write, "") # Add a blank line for readability

    unique_const_names = Set{String}()
 
    for item in data
        if isa(item, JSON3.Object) && haskey(item, "Key") && isa(item.Key, String)
            original_key_value = item.Key
            
            # Transform to constant name
            processed_key = strip(original_key_value) 
            
            const_name_base = if startswith(uppercase(processed_key), "$(uppercase(name))_")
                processed_key[length("$(name)_") + 1:end]
            else
                processed_key
            end
            
            const_name = uppercase(replace(const_name_base, r"[^a-zA-Z0-9_]" => ""))
            
            if isempty(const_name) || !isletter(first(const_name)) && !startswith(first(const_name), '_')
                @warn "Could not generate a valid constant name for key: '$(original_key_value)'. Processed base: '$(const_name_base)'. Skipping."
                continue
            end

            if const_name in unique_const_names
                @warn "Duplicate constant name generated: $(const_name) for key '$(original_key_value)'. Skipping previous definition or this one."
                continue
            end
            push!(unique_const_names, const_name)

            # Escape backslashes first, then double quotes for the string literal
            escaped_original_key_value = replace(replace(original_key_value, "\\" => "\\\\"), "\"" => "\\\"")
            push!(lines_to_write, "const $(const_name) = \"$(strip(uppercase(escaped_original_key_value)))\"")
        else
            @warn "Skipping item without a valid 'Key' field or item is not an object: $(item)"
        end
    end

    try
        open(output_file_path, "w") do f
            for line in lines_to_write
                println(f, line)
            end
        end
        println("Successfully generated $(output_file_path)")
    catch e
        @error "Failed to write to output file $(output_file_path): $(e)"
    end
end

function generate_structs_file(name::String)
    # Determine paths relative to this script's location
    project_battler_dir = joinpath(@__DIR__, "..") 
    
    json_file_path = joinpath(project_battler_dir, "assets", "game-data-manager", "json", "$(name).json")
    output_file_path = joinpath(project_battler_dir, "scripts", "generated-types", "$(name)Structs.jl")

    if !isfile(json_file_path)
        @error "Input JSON file not found: $(json_file_path)"
        println("Please ensure the JSON file exists at the expected location.")
        return
    end

    json_string = ""
    try
        json_string = read(json_file_path, String)
    catch e
        @error "Failed to read JSON file $(json_file_path): $(e)"
        return
    end
    
    data = nothing
    try
        data = JSON3.read(json_string)
    catch e
        @error "Failed to parse JSON data from $(json_file_path): $(e)"
        return
    end

    if isempty(data)
        @error "No data found in JSON file"
        return
    end

    # Analyze all items to determine field types
    field_types = Dict{String, Type}()
    all_fields = Set{String}()
    
    for item in data
        if isa(item, JSON3.Object)
            for (key, value) in pairs(item)
                field_name = String(key)
                push!(all_fields, field_name)
                
                # Determine Julia type based on JSON value
                #@debug("value: $(value)")
                julia_type = if value === nothing
                    Union{String, Nothing}  # Default for null values
                elseif isa(value, String)
                    String
                elseif isa(value, Bool)
                    Bool
                elseif isa(value, Integer)
                    Int64
                elseif isa(value, AbstractFloat)
                    Float64
                else
                    String  # Fallback to String for unknown types
                end
                
                # If we've seen this field before, make it a union type if types differ
                if haskey(field_types, field_name)
                    existing_type = field_types[field_name]
                    if existing_type != julia_type
                        # Create union type to handle different types for the same field
                        if existing_type == Union{String, Nothing} || julia_type == Union{String, Nothing}
                            field_types[field_name] = Union{String, Nothing}
                        elseif existing_type == String || julia_type == String
                            field_types[field_name] = Union{String, Nothing}
                        else
                            field_types[field_name] = Union{existing_type, julia_type, Nothing}
                        end
                    end
                else
                    field_types[field_name] = julia_type
                end
            end
        end
    end

    # Convert field names to valid Julia identifiers
    function to_julia_field_name(field_name::String)
        # Convert to lowercase and replace non-alphanumeric characters with underscores
        clean_name = lowercase(replace(field_name, r"[^a-zA-Z0-9_]" => "_"))
        # Remove leading/trailing underscores and collapse multiple underscores
        clean_name = replace(clean_name, r"^_+|_+$" => "")
        clean_name = replace(clean_name, r"_+" => "_")
        # Ensure it starts with a letter or underscore
        if !isempty(clean_name) && !isletter(first(clean_name)) && first(clean_name) != '_'
            clean_name = "_" * clean_name
        end
        return isempty(clean_name) ? "_field" : clean_name
    end

    # Generate the struct definition
    lines_to_write = String[]
    push!(lines_to_write, "# This file is auto-generated by generate_constants.jl. Do not edit manually.")
    push!(lines_to_write, "# Source JSON: $(basename(json_file_path))")
    push!(lines_to_write, "include(\"$(joinpath("..", "utils", "$(name)Constants.jl"))\")")
    push!(lines_to_write, "include(\"$(joinpath("..", "shared-types", "BaseStruct.jl"))\")")
    push!(lines_to_write, "")
    
    # Struct definition
    push!(lines_to_write, "abstract type $(name[1:end-1]) <: BaseStruct end")

    # Generate constructor functions for each item
    constructor_function_names = String[]
    for item in data
        if isa(item, JSON3.Object) && haskey(item, "Key") && isa(item.Key, String)
            @debug "item: $(item)"
            # Enemies: include all JSON rows so pattern data (e.g. Bash, Weaken) exists even when not yet spawnable.
            skip_unavailable = false #haskey(item, "Currently_Available_In_Game") && !item.Currently_Available_In_Game
            if name != "Enemies" && skip_unavailable
                continue
            end
            key_value = item.Key
            
            # Generate function name from key
            func_name_base = if startswith(key_value, "$(name)_")
                key_value[length("$(name)_") + 1:end]
            else
                key_value
            end
            
            # Clean function name
            func_name = replace(func_name_base, r"[^a-zA-Z0-9_]" => "_")
            func_name = replace(func_name, r"^_+|_+$" => "")
            func_name = replace(func_name, r"_+" => "_")
            
            if isempty(func_name) || (!isletter(first(func_name)) && first(func_name) != '_')
                @warn "Could not generate valid function name for key: '$(key_value)'. Skipping."
                continue
            end

            struct_name = func_name
            push!(lines_to_write, "struct $(lowercase(struct_name)) <: $(name[1:end-1])")
            
            field_mapping = Dict{String, String}()

            for field in all_fields
                julia_field = to_julia_field_name(field)
                field_mapping[field] = julia_field
                field_type = field_types[field]
                push!(lines_to_write, "    $(julia_field)::$(field_type)")
            end
            
            push!(lines_to_write, "end")
            push!(lines_to_write, "")

            push!(constructor_function_names, func_name)
            
            # Build constructor arguments
            constructor_args = String[]
            for field in all_fields
                julia_field = field_mapping[field]
                value = get(item, field, nothing)
                field_type = field_types[field]

                # Format value for Julia code
                formatted_value = if value === nothing
                    "nothing"
                elseif field == "Key"
                    value = uppercase(value)
                elseif isa(value, String)
                    "\"$(replace(replace(value, "\\" => "\\\\"), "\"" => "\\\""))\""
                elseif isa(value, Bool)
                    string(value)
                elseif isa(value, Number)
                    # If field type expects String, convert number to quoted string
                    if field_type == String || field_type == Union{String, Nothing}
                        "\"$(string(value))\""
                    else
                        string(value)
                    end
                else
                    "\"$(string(value))\""
                end
                
                push!(constructor_args, formatted_value)
            end
            
            push!(lines_to_write, "$(lowercase(func_name))() = $(lowercase(struct_name))($(join(constructor_args, ", ")))")
            push!(lines_to_write, "")
        end
    end

    # Generate export array
    if !isempty(constructor_function_names)
        push!(lines_to_write, "# Array of all $(name[1:end-1]) items")
        array_name = "ALL_$(uppercase(name))"
        function_calls = [func_name * "()" for func_name in constructor_function_names]
        push!(lines_to_write, "const $(array_name) = Dict{String, $(name[1:end-1])}(")
        for (i, func_call) in enumerate(function_calls)
            if i == length(function_calls)
                push!(lines_to_write, "    $(uppercase(func_call[1:end-2])) => $(lowercase(func_call))")
            else
                push!(lines_to_write, "    $(uppercase(func_call[1:end-2])) => $(lowercase(func_call)),")
            end
        end
        push!(lines_to_write, ")")
        push!(lines_to_write, "")
    end

    # Ensure output directory exists
    output_dir = dirname(output_file_path)
    if !isdir(output_dir)
        mkpath(output_dir)
    end

    try
        open(output_file_path, "w") do f
            for line in lines_to_write
                println(f, line)
            end
        end
        println("Successfully generated $(output_file_path)")
    catch e
        @error "Failed to write to output file $(output_file_path): $(e)"
    end
end

